"""Multi-agent root-cause analysis: how sure is the team, and which agent is wrong?

A checkout service starts returning 5xx errors. Five LLM agents investigate, each with its
own slice of the evidence (application logs, metrics, the deploy diff, network flow logs,
past incident reports). Each agent's reply becomes a belief function over the causes, in one
of two ways:

  verbalised (API models)   the agent names a *set* of plausible causes and a confidence,
                            {"causes": ["deploy", "database"], "confidence": 0.7}. A set is a
                            focal set: m(set) = conf, m(Θ) = 1 − conf. "Not the network" is the
                            set of the other four, and an empty set is the vacuous mass.
  scored (local models)     no self-reported confidence: score every cause name under the model
                            after the prompt. p(cause) gives a possibility contour π = p / max p
                            (causes close to the top stay plausible), and the probability the
                            model puts on *any* cause name is its reliability. If the model would
                            rather write something else, that remainder goes to Θ.

What the belief layer adds on top of a majority vote:

    blame     Shapley blame names the agent that contradicts the rest (here: the one that
              pattern-matched an old DNS incident) and discounts it before fusing
    abstain   the team answer is the set of causes no other cause beats (Walley maximality).
              Early on, with two replies in, it is "deploy | database | dns": wait or escalate
    debate    after a debate round the agents have read each other, so round 2 is not new
              evidence. Dempster's rule counts the echo again and becomes certain; the cautious
              rule (idempotent) leaves the team belief about where it was

The same question comes up within round 1. ``--rule dempster`` (the default) treats the
agents as independent witnesses: four agents that each give deploy 0.5–0.9 fuse to about 0.99.
That is right for different models, or for agents whose evidence does not overlap. Five
prompts on one base model share most of what they know, so they are not independent;
``--rule cautious`` combines them without counting that shared knowledge twice. The team
belief is then about as strong as the strongest agent, not the product of all of them.

    python examples/multi_agent.py                                  # scripted replies, no model
    python examples/multi_agent.py --live                           # Claude agents (pip install anthropic)
    python examples/multi_agent.py --local Qwen/Qwen2.5-0.5B-Instruct   # scored by a local model
    python examples/multi_agent.py --local ... --log replies.json
    python examples/multi_agent.py --replay replies.json --temperature 5 --rule cautious

The scripted replies are hand-written to illustrate the mechanics, not recorded from a model.
"""

