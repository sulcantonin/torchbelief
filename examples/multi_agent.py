# ---- replies → belief functions ----------------------------------------------------------------

def to_mass(reply, frame, temperature=1.0):
    """A reply as a mass function: verbalised {causes, confidence} → simple support on the set;
    scored {probs, coverage} → consonant mass with contour p / max p, discounted by coverage.

    ``temperature`` > 1 flattens scored probabilities, p ∝ p^(1/T), the same as dividing the
    log-probabilities by T. Instruct models put nearly all mass on one token, so T = 1 makes
    every scored reply close to certain."""
    if "probs" in reply:
        p = torch.tensor([reply["probs"][c] for c in frame.names], dtype=D).pow(1 / temperature)
        m = tb.Capacity.from_possibility(p / p.max(), frame).mass()
        return tb.discount(m, float(reply["coverage"]), frame)
    known = [c for c in reply.get("causes", []) if c in frame.names]
    if not known:
        return tb.vacuous(frame, dtype=D)
    conf = min(max(float(reply.get("confidence", 0.0)), 0.0), 1.0)
    return tb.simple_support(frame, frame.subset(known), conf, dtype=D)


def label(m, frame):
    """The causes no other cause beats, "a | b", or "?" if nothing can be ruled out."""
    keep = choice.maximal_acts(tb.Capacity.from_mass(m, frame), torch.eye(frame.n, dtype=D))
    if bool(keep.all()):
        return "?"
    return " | ".join(n for n, k in zip(frame.names, keep) if k)


def describe(reply):
    if "probs" in reply:
        top = sorted(reply["probs"].items(), key=lambda kv: -kv[1])[:3]
        return (", ".join(f"{c} {p:.2f}" for c, p in top) + f"   on-frame {reply['coverage']:.2f}")
    return f"{' | '.join(reply['causes']) or '?':34s} conf {reply['confidence']:.2f}   {reply.get('reason', '')}"


def vote(reply):
    """The agent's single answer for a majority vote, or None if it named several causes."""
    if "probs" in reply:
        return max(reply["probs"], key=reply["probs"].get)
    return reply["causes"][0] if len(reply["causes"]) == 1 else None


def fuse(masses, frame, rule="dempster"):
    """Blame-discount the agents, then fuse. Returns (fused mass, reliability α per agent)."""
    caps = [tb.Capacity.from_mass(m, frame) for m in masses]
    fixed, alpha = I.blame_discount(caps)
    m, _ = tb.combine([c.mass() for c in fixed], frame, rule)
    return m, alpha


def show(title, m, frame):
    bel, pl = tb.interval(m, frame)
    cells = "  ".join(f"{n} [{b:.2f}, {p:.2f}]" for n, b, p in zip(frame.names, bel, pl))
    lab = label(m, frame)
    print(f"  {title:30s} → {lab:24s} {cells}")
    if lab == "?" or "|" in lab:
        print(f"  {'':30s}   (no single cause: wait for more evidence or escalate to a human)")


# ---- the analysis --------------------------------------------------------------------------------

def report(replies, temperature=1.0, rule="dempster"):
    frame = tb.Frame(len(CAUSES), names=CAUSES)
    r1, r2 = replies["round1"], replies["round2"]
    names = list(r1)
    m1 = [to_mass(r1[a], frame, temperature) for a in names]

    print("Round 1: independent replies")
    for a in names:
        print(f"  {a:8s} {describe(r1[a])}")

    votes = [v for v in map(vote, r1.values()) if v is not None]
    best = max(set(votes), key=votes.count)
    print(f"\nMajority vote: {best} ({votes.count(best)} of {len(votes)} single answers), "
          "no sense of how sure the team is")

    phi = I.shapley_blame([tb.Capacity.from_mass(m, frame) for m in m1])
    print("\nShapley blame (who contradicts the others)")
    for a, p in zip(names, phi):
        print(f"  {a:8s} {float(p):.3f} {'█' * int(40 * float(p))}")

    print(f"\nTeam belief ({rule}): causes no other cause beats, then [Bel, Pl] per cause")
    m, alpha = fuse(m1, frame, rule)
    show("all agents, blame-discounted", m, frame)
    m_raw, _ = tb.combine(m1, frame, "yager")
    show("all agents, Yager, no discount", m_raw, frame)
    early = [names.index("logs"), names.index("history")]
    m_early, _ = fuse([m1[i] for i in early], frame, rule)
    show("early: only logs + history", m_early, frame)

    print("\nRound 2: a debate round, every agent has read the others")
    for a in names:
        print(f"  {a:8s} {describe(r2[a])}")
    m2 = [tb.discount(to_mass(r2[a], frame, temperature), alpha[i], frame) for i, a in enumerate(names)]
    print("Fusing the round 2 replies into the round 1 team belief:")
    for rule, note in (("dempster", "counts the echo as new evidence"),
                       ("cautious", "idempotent: an echo adds nothing")):
        mr, _ = tb.combine([m] + m2, frame, rule)
        show(f"team + round 2, {rule}", mr, frame)
        print(f"  {'':30s}   m(Θ) = {float(mr[..., frame.theta]):.4f}   ({note})")


# ---- prompts shared by both backends -------------------------------------------------------------

def prompt(evidence, others=None):
    text = f"Incident: {INCIDENT}\n\nYour evidence:\n{evidence}"
    if others:
        text += "\n\nReplies of the other agents in round 1:\n" + "\n".join(
            f"- {a}: {describe(r)}" for a, r in others.items())
        text += "\n\nReconsider and give your updated answer."
    return text


def run(ask):
    """Two rounds over all agents; ``ask(evidence, others)`` returns one reply dict."""
    r1 = {a: ask(ev, None) for a, ev in AGENTS.items()}
    r2 = {a: ask(ev, {b: r for b, r in r1.items() if b != a}) for a, ev in AGENTS.items()}
    return {"round1": r1, "round2": r2}


# ---- Claude agents: verbalised set + confidence ----------------------------------------------------

SCHEMA = {
    "type": "object",
    "properties": {
        "causes": {"type": "array", "items": {"type": "string", "enum": CAUSES}},
        "confidence": {"type": "number"},
        "reason": {"type": "string"},
    },
    "required": ["causes", "confidence", "reason"],
    "additionalProperties": False,
}

SYSTEM = (f"You are one agent in an incident-response team. Possible root causes: {', '.join(CAUSES)}.\n"
          "Answer only from the evidence you are given. Return every cause your evidence leaves "
          "plausible (one cause if it is clear, several if you cannot separate them, an empty list "
          "if your evidence says nothing about the cause), a confidence in [0, 1] that the true "
          "cause is in your list, and a one-sentence reason.")


def claude_agent(model):
    import anthropic
    client = anthropic.Anthropic()

    def ask(evidence, others):
        response = client.beta.messages.create(
            model=model,
            max_tokens=16000,
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
            output_config={"effort": "low", "format": {"type": "json_schema", "schema": SCHEMA}},
            system=SYSTEM,
            messages=[{"role": "user", "content": prompt(evidence, others)}],
        )
        if response.stop_reason == "refusal":
            return dict(causes=[], confidence=0.0, reason="(declined)")
        return json.loads(next(b.text for b in response.content if b.type == "text"))
    return ask


# ---- local agents: scored cause names ---------------------------------------------------------------

LOCAL_SYSTEM = (f"You are one agent in an incident-response team. Possible root causes: {', '.join(CAUSES)}.\n"
                "Answer only from the evidence you are given, with the single most likely root cause "
                "as one word from the list.")


def scored_reply(logprob, context):
    """Reply from token log-probabilities: ``logprob(context, text)`` = log P(text | context).

    p(cause) sums the spellings "deploy" / "Deploy". ``coverage`` = Σ p is how much of the
    model's next answer falls on the frame at all; the rest is treated as ignorance."""
    lp = torch.stack([torch.logsumexp(torch.stack([logprob(context, s) for s in (c, c.capitalize())]), 0)
                      for c in CAUSES]).double()
    p = lp.exp()
    return dict(probs=dict(zip(CAUSES, (p / p.sum()).tolist())), coverage=float(p.sum().clamp(max=1)))


def local_agent(name):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(name)
    lm = AutoModelForCausalLM.from_pretrained(name, dtype=torch.float32).eval()

    @torch.no_grad()
    def logprob(context, text):
        n = len(tok(context, add_special_tokens=False).input_ids)
        ids = tok(context + text, return_tensors="pt", add_special_tokens=False).input_ids
        lp = lm(ids).logits[0, n - 1:-1].log_softmax(-1)
        return lp.gather(-1, ids[0, n:, None]).sum()

    def ask(evidence, others):
        context = tok.apply_chat_template([{"role": "system", "content": LOCAL_SYSTEM},
                                           {"role": "user", "content": prompt(evidence, others)}],
                                          tokenize=False, add_generation_prompt=True)
        return scored_reply(logprob, context)
    return ask


def main():
    ap = argparse.ArgumentParser(description="torchbelief over a team of LLM agents")
    ap.add_argument("--live", action="store_true", help="Claude agents (verbalised sets + confidence)")
    ap.add_argument("--model", default="claude-opus-5-5", help="Claude model for --live")
    ap.add_argument("--local", metavar="HF_MODEL", help="local causal LM that scores the cause names")
    ap.add_argument("--temperature", type=float, default=1.0,
                    help="calibration temperature for scored (local) replies; > 1 flattens them")
    ap.add_argument("--rule", default="dempster", choices=["dempster", "cautious"],
                    help="round 1 team fusion: dempster for independent agents, cautious for "
                         "agents sharing one base model")
    ap.add_argument("--log", help="save the agents' replies (JSON) here")
    ap.add_argument("--replay", help="run the belief layer over saved replies")
    a = ap.parse_args()
    if a.replay:
        replies = json.load(open(a.replay))
    elif a.local:
        replies = run(local_agent(a.local))
    elif a.live:
        replies = run(claude_agent(a.model))
    else:
        replies = SCRIPTED
    if a.log:
        json.dump(replies, open(a.log, "w"), indent=1)
    report(replies, a.temperature, a.rule)


if __name__ == "__main__":
    main()
